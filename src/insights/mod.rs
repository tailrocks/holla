pub fn detect(spec: &InsightSpec, probe: &Probe) -> bool {
    match spec.detect {
        Detect::Always => true,
        Detect::ToolOnPath(tool) => probe.tools.contains(tool),
        Detect::DirExists => {
            expand_roots_with_xdg(spec, &probe.home, probe.xdg_cache_home.as_deref())
                .iter()
                .any(|path| probe.existing_dirs.contains(path))
        }
        Detect::ToolOrDir(tool) => {
            probe.tools.contains(tool)
                || expand_roots_with_xdg(spec, &probe.home, probe.xdg_cache_home.as_deref())
                    .iter()
                    .any(|path| probe.existing_dirs.contains(path))
        }
    }
}

pub fn expand_roots(spec: &InsightSpec, home: &Path) -> Vec<PathBuf> {
    expand_roots_with_xdg(spec, home, None)
}

pub fn expand_roots_with_xdg(
    spec: &InsightSpec,
    home: &Path,
    xdg_cache_home: Option<&Path>,
) -> Vec<PathBuf> {
    spec.roots
        .iter()
        .filter_map(|root| match root {
            RootPattern::Home(relative) => Some(home.join(relative)),
            RootPattern::XdgCache(relative) => Some(
                xdg_cache_home
                    .map_or_else(|| home.join(".cache"), Path::to_path_buf)
                    .join(relative),
            ),
            RootPattern::PnpmStore => Some(home.join("Library/pnpm/store")),
            RootPattern::Special => None,
        })
        .collect()
}

pub fn is_old_enough(mtime: SystemTime, min_age_days: Option<u32>, now: SystemTime) -> bool {
    let Some(days) = min_age_days else {
        return true;
    };
    now.duration_since(mtime).unwrap_or(Duration::ZERO)
        >= Duration::from_secs(u64::from(days) * 24 * 60 * 60)
}

pub fn spec(id: &str) -> Option<&'static InsightSpec> {
    REGISTRY.iter().find(|entry| entry.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cleanup::validate;

    fn fake_probe() -> Probe {
        Probe {
            home: "/tmp/fake-home".into(),
            xdg_cache_home: None,
            tools: HashSet::new(),
            existing_dirs: HashSet::new(),
        }
    }

    #[test]
    fn registry_ids_are_unique_and_explanations_nonempty() {
        let mut ids = HashSet::new();
        assert!(REGISTRY.iter().all(|entry| ids.insert(entry.id)));
        assert!(
            REGISTRY
                .iter()
                .all(|entry| !entry.explain.trim().is_empty())
        );
    }

    #[test]
    fn concrete_roots_expand_below_injected_home() {
        let home = Path::new("/tmp/fake-home");
        for entry in REGISTRY {
            for root in expand_roots(entry, home) {
                assert!(root.starts_with(home), "{}: {}", entry.id, root.display());
            }
        }
    }

    #[test]
    fn xdg_cache_override_is_honored() {
        let uv = spec("uv.cache").unwrap();
        assert_eq!(
            expand_roots_with_xdg(uv, Path::new("/home/me"), Some(Path::new("/cache"))),
            [PathBuf::from("/cache/uv")]
        );
    }

    #[test]
    fn detection_uses_injected_tool_and_directory_facts() {
        let mut probe = fake_probe();
        assert!(!detect(spec("brew.cache").unwrap(), &probe));
        probe.tools.insert("brew".into());
        assert!(detect(spec("brew.cache").unwrap(), &probe));
        let derived = expand_roots(spec("xcode.derived-data").unwrap(), &probe.home).remove(0);
        probe.existing_dirs.insert(derived);
        assert!(detect(spec("xcode.derived-data").unwrap(), &probe));
    }

    #[test]
    fn age_gate_treats_future_mtime_as_recent() {
        let now = SystemTime::UNIX_EPOCH + Duration::from_secs(100 * 86_400);
        assert!(is_old_enough(
            now - Duration::from_secs(31 * 86_400),
            Some(30),
            now
        ));
        assert!(!is_old_enough(
            now - Duration::from_secs(29 * 86_400),
            Some(30),
            now
        ));
        assert!(!is_old_enough(now + Duration::from_secs(1), Some(30), now));
        assert!(is_old_enough(now, None, now));
    }

    #[test]
    fn never_touch_user_paths_are_rejected() {
        let Some(home) = dirs::home_dir() else { return };
        for relative in [
            ".Trash/item",
            "Library/Mobile Documents/com~apple~CloudDocs/file",
            "Library/Mobile Documents.old/file",
            "Library/Keychains/login.keychain-db",
            "Library/Application Support/Google/Chrome/Profile 1",
            "Library/Safari/History.db",
            "Library/Containers/com.docker.docker/Data/vms/0/data/Docker.raw",
        ] {
            let path = home.join(relative);
            assert!(validate(&path).is_err(), "{}", path.display());
        }
    }
}
