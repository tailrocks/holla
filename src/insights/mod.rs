#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Safety {
    Rebuildable,
    CacheOldOnly,
    ReviewFirst,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RootPattern {
    Home(&'static str),
    XdgCache(&'static str),
    PnpmStore,
    Special,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Detect {
    Always,
    ToolOnPath(&'static str),
    DirExists,
    ToolOrDir(&'static str),
}

#[derive(Debug)]
pub struct InsightSpec {
    pub id: &'static str,
    pub title: &'static str,
    pub explain: &'static str,
    pub safety: Safety,
    pub roots: &'static [RootPattern],
    pub min_age_days: Option<u32>,
    pub detect: Detect,
    pub skip_if_running: Option<&'static str>,
}

#[derive(Debug, Clone)]
pub struct Probe {
    pub home: PathBuf,
    pub xdg_cache_home: Option<PathBuf>,
    pub tools: HashSet<String>,
    pub existing_dirs: HashSet<PathBuf>,
}

impl Probe {
    pub fn current() -> Option<Self> {
        let home = dirs::home_dir()?;
        let xdg_cache_home = std::env::var_os("XDG_CACHE_HOME")
            .filter(|value| !value.is_empty())
            .map(PathBuf::from);
        let tools = TOOL_NAMES
            .iter()
            .filter(|tool| which::which(tool).is_ok())
            .map(|tool| (*tool).to_owned())
            .collect();
        let mut probe = Self {
            home,
            xdg_cache_home,
            tools,
            existing_dirs: HashSet::new(),
        };
        for spec in REGISTRY {
            probe.existing_dirs.extend(
                expand_roots_with_xdg(spec, &probe.home, probe.xdg_cache_home.as_deref())
                    .into_iter()
                    .filter(|path| path.is_dir()),
            );
        }
        Some(probe)
    }
}

